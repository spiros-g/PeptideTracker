package gr.peptidetracker.app.i18n

import java.util.Locale

@Volatile
private var languageOverride: String? = null

fun setLanguageOverride(value: String?) {
    languageOverride = value
        ?.trim()
        ?.lowercase()
        ?.takeIf { it == "el" || it == "en" }
}

fun currentLanguageTag(): String =
    languageOverride ?: Locale.getDefault().language.lowercase()

fun isGreekLanguage(): Boolean =
    currentLanguageTag() == "el"

fun t(greek: String): String {
    if (isGreekLanguage()) return greek

    return uiEnglishTranslations[greek]
        ?: catalogEnglishTranslations[greek]
        ?: dynamicEnglish(greek)
        ?: greek
}

private fun dynamicEnglish(value: String): String? {
    if (value.startsWith("Νέα έκδοση ")) {
        return "New version " + value.removePrefix("Νέα έκδοση ")
    }
    if (value.startsWith("Κάθε ") && value.endsWith(" ημέρες")) {
        return "Every " + value.removePrefix("Κάθε ").removeSuffix(" ημέρες") + " days"
    }
    return null
}

