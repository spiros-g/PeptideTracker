package gr.peptidetracker.app.data

import android.net.Uri

data class Study(
    val title: String,
    val source: String,
    val url: String
)

data class PeptideInfo(
    val id: String,
    val name: String,
    val alias: String,
    val category: String,
    val status: String,
    val overview: String,
    val research: String,
    val mechanism: String,
    val warning: String,
    val studies: List<Study>
)

private fun pubmed(query: String) =
    "https://pubmed.ncbi.nlm.nih.gov/?term=" + Uri.encode(query)

private fun trials(query: String) =
    "https://clinicaltrials.gov/search?term=" + Uri.encode(query)

private fun peptide(
    id: String,
    name: String,
    alias: String,
    category: String,
    status: String,
    overview: String,
    research: String,
    mechanism: String,
    warning: String,
    searchTerm: String = name
) = PeptideInfo(
    id = id,
    name = name,
    alias = alias,
    category = category,
    status = status,
    overview = overview,
    research = research,
    mechanism = mechanism,
    warning = warning,
    studies = listOf(
        Study("Δημοσιευμένη βιβλιογραφία", "PubMed", pubmed(searchTerm)),
        Study("Καταχωρημένες κλινικές μελέτες", "ClinicalTrials.gov", trials(searchTerm))
    )
)

